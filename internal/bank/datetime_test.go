func TestReviewCycle2DatetimeGrammarBoundary(t *testing.T) {
	for _, sep := range []string{"T", " "} {
		for _, clock := range []string{"1", "1:30", "1:30:00", "12:1", "12:1:00", "12:30:1", "24:00:00", "12:60:00", "12:30:60"} {
			for _, zone := range []string{"", "Z", "+03:00", "+0300", "+02:30:17"} {
				text := "2026-08-01" + sep + clock + zone
				t.Run(text, func(t *testing.T) { reviewCycle2InvalidDatetime(t, text) })
			}
		}
	}
	for _, text := range []string{"2026-08-01T12:30:00ZZ", "2026-08-01T12:30:00Z\n", "2026-08-01T12:30:00Z ", "2026-08-01T00:00:00+3:00", "2026-8-01T12:30:00Z"} {
		t.Run(text, func(t *testing.T) { reviewCycle2InvalidDatetime(t, text) })
	}
	// Existing supported reduced clock, dot/comma fraction, separator and offset
	// forms must survive the width gate. This is an explicit subset, not all ISO.
	for text, want := range map[string]string{
		"2026-08-01":                       "2026-08-01T00:00:00+03:00",
		"2026-08-01T12":                    "2026-08-01T12:00:00+03:00",
		"2026-08-01 12":                    "2026-08-01T12:00:00+03:00",
		"2026-08-01T12:30":                 "2026-08-01T12:30:00+03:00",
		"2026-08-01 12:30Z":                "2026-08-01T12:30:00Z",
		"2026-08-01T12+03":                 "2026-08-01T12:00:00+03:00",
		"2026-08-01 12:30+0300":            "2026-08-01T12:30:00+03:00",
		"2026-08-01T12:30:00-03:30":        "2026-08-01T12:30:00-03:30",
		"2026-08-01 12:30:00,123456+03:00": "2026-08-01T12:30:00.123456+03:00",
		"2026-08-01T12:30:00.123456Z":      "2026-08-01T12:30:00.123456Z",
		"2026-08-01T12:30:00+00:60":        "2026-08-01T12:30:00+01:00",
	} {
		t.Run("supported/"+text, func(t *testing.T) {
			expected, err := time.Parse(time.RFC3339Nano, want)
			if err != nil {
				t.Fatal(err)
			}
			got, err := domainISOMoment(text)
			if err != nil || !got.Equal(expected) {
				t.Fatalf("supported source form changed: %v, %v; want %v", got, err, expected)
			}
			f, err := NewTimeFilter(text, text)
			if err != nil || !f.Contains(text) {
				t.Fatalf("supported source form lost filter bounds: %+v, %v", f, err)
			}
		})
	}
}

func TestReviewCycle2DatetimeMicrosecondPrecision(t *testing.T) {
	zones := []struct {
		text   string
		offset int
	}{{"", 10800}, {"Z", 0}, {"+03", 10800}, {"+0300", 10800}, {"+03:00", 10800}, {"-03:30", -12600}, {"+02:30:17", 9017}, {"-02:30:17", -9017}}
	fractions := []struct {
		left, right string
		microsecond int
	}{{"1234567", "1234569", 123456}, {"123456789123", "123456", 123456}, {"0000009", "0000001", 0}, {"9999999", "9999991", 999999}}
	for _, sep := range []string{"T", " "} {
		for _, decimal := range []string{".", ","} {
			for _, zone := range zones {
				for _, fraction := range fractions {
					left := "2026-08-01" + sep + "12:30:00" + decimal + fraction.left + zone.text
					right := "2026-08-01" + sep + "12:30:00" + decimal + fraction.right + zone.text
					t.Run(left, func(t *testing.T) {
						want := time.Date(2026, 8, 1, 12, 30, 0, fraction.microsecond*1000, time.FixedZone("", zone.offset))
						for _, text := range []string{left, right} {
							got, err := domainISOMoment(text)
							if err != nil || !got.Equal(want) || got.Nanosecond()%1000 != 0 || !OperationSortKey(text).Equal(want) {
								t.Errorf("source microsecond truncation changed: %s -> %v (%v); want %v", text, got, err, want)
							}
						}
						for _, text := range []string{left, right} {
							f, err := NewTimeFilter(text, text)
							if err != nil {
								t.Fatal(err)
							}
							if f.From == nil || f.To == nil || !f.From.Equal(want) || !f.To.Equal(want) || !f.Contains(left) || !f.Contains(right) {
								t.Errorf("source-equal timestamps lost inclusive bounds: %+v", f)
							}
							from, to := f.RequestBounds()
							expected := want.In(domainMoscow).Format("02.01.2006T15:04:05")
							if from != expected || to != expected {
								t.Errorf("request seconds rounded or changed: %q/%q; want %q", from, to, expected)
							}
						}
					})
				}
			}
		}
	}
	f, err := NewTimeFilter("2026-08-01T12:30:00.1234567+03:00", "2026-08-01T12:30:00.1234569+03:00")
	if err != nil {
		t.Fatal(err)
	}
	for _, text := range []string{"2026-08-01T12:30:00.1234559+03:00", "2026-08-01T12:30:00.123457+03:00"} {
		if f.Contains(text) {
			t.Error("distinct neighboring microsecond was merged")
		}
	}
	// Native values remain native: parsing normalizes source text, but must not
	// rewrite the caller's explicit nanosecond bound or its location.
	native := time.Date(2026, 8, 1, 12, 30, 0, 123456700, time.FixedZone("native", 10800))
	before := native
	direct := TimeFilter{From: &native, To: &native}
	if direct.Contains("2026-08-01T12:30:00.1234567+03:00") || native != before {
		t.Fatal("direct native nanosecond bounds were normalized or mutated")
	}
}

func reviewCycle2InvalidDatetime(t *testing.T, text string) {
	t.Helper()
	if key := OperationSortKey(text); !key.Equal(time.Time{}) || key.Location() != time.UTC {
		t.Errorf("source-invalid ISO spelling acquired a sorting key: %v", key)
	}
	if (TimeFilter{}).Contains(text) {
		t.Error("source-invalid spelling matched unbounded history")
	}
	for _, bounds := range [][2]string{{text, ""}, {"", text}, {"2026-08-01", text}} {
		f, err := NewTimeFilter(bounds[0], bounds[1])
		var pe *ParseError
		if !errors.As(err, &pe) || pe.Field() != "date" || f.From != nil || f.To != nil {
			t.Errorf("invalid spelling published bounds or unsafe error: %+v, %v", f, err)
		} else if strings.Contains(err.Error(), text) {
			t.Error("date error echoed input")
		}
	}
}

// Raw-source differential controls cover before/at/after every Moscow transition
// discovered between 1880 and 2027, including offset seconds and non-hour jumps.
func TestReviewCycle2MoscowNaiveFoldGap(t *testing.T) {
	for _, tc := range reviewCycle2MoscowSourceCases {
		t.Run(tc.text, func(t *testing.T) {
			for _, fraction := range []string{"", ".1234569"} {
				text := tc.text + fraction
				key, err := domainISOMoment(text)
				micro := 0
				if fraction != "" {
					micro = 123456
				}
				_, off := key.Zone()
				if err != nil || key.Unix() != tc.unixSecond || off != tc.offset || key.Nanosecond() != micro*1000 || key.Format("2006-01-02T15:04:05") != tc.text {
					t.Errorf("source fold=0 wall attachment changed: %v (%v); want wall %s, offset %d, Unix %d, micro %d", key, err, tc.text, tc.offset, tc.unixSecond, micro)
				}
				f, err := NewTimeFilter(text, text)
				if err != nil {
					t.Fatal(err)
				}
				if !f.Contains(text) || f.From == nil || f.To == nil || !f.From.Equal(key) || !f.To.Equal(key) {
					t.Error("naive attached bound did not retain its instant")
				}
				from, to := f.RequestBounds()
				wall, err := time.Parse("2006-01-02T15:04:05", tc.text)
				if err != nil {
					t.Fatal(err)
				}
				bank := wall.Format("02.01.2006T15:04:05")
				if from != bank || to != bank {
					t.Errorf("naive request wall normalized across transition: %q/%q; want %q", from, to, bank)
				}
				expected := time.Date(wall.Year(), wall.Month(), wall.Day(), wall.Hour(), wall.Minute(), wall.Second(), 0, time.FixedZone("source", tc.offset))
				isoFrom, isoTo := f.ISOBounds()
				if isoFrom != domainISOFormat(expected) || isoTo != domainISOFormat(expected) {
					t.Errorf("naive ISO wall/offset lost: %q/%q; want %s", isoFrom, isoTo, domainISOFormat(expected))
				}
				// Copying the native value retains its wall representation without registry
				// identity, mutation or a foreign TimeFilter layout.
				copied := *f.From
				copyFilter := TimeFilter{From: &copied, To: &copied}
				before := copied
				copiedFrom, copiedTo := copyFilter.RequestBounds()
				if copiedFrom != bank || copiedTo != bank || copied != before || !copyFilter.Contains(text) {
					t.Error("copied native value lost wall representation or was mutated")
				}
			}
			wall, err := time.Parse("2006-01-02T15:04:05", tc.text)
			if err != nil {
				t.Fatal(err)
			}
			bank := wall.Format("02.01.2006T15:04:05")
			payload := map[string]any{"body": map[string]any{"operations": []any{map[string]any{"uohId": "synthetic-cycle2", "date": bank}}}}
			original := payload["body"].(map[string]any)["operations"].([]any)[0].(map[string]any)
			operations, err := ParseOperations(payload)
			expected := time.Date(wall.Year(), wall.Month(), wall.Day(), wall.Hour(), wall.Minute(), wall.Second(), 0, time.FixedZone("source", tc.offset))
			if err != nil || len(operations) != 1 || operations[0].Date != domainISOFormat(expected) {
				t.Errorf("bank date fold/gap attachment changed: %+v, %v; want %s", operations, err, domainISOFormat(expected))
			}
			if original["date"] != bank || original["uohId"] != "synthetic-cycle2" {
				t.Error("input operation map mutated")
			}
		})
	}
}

