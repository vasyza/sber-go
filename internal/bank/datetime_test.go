func FuzzReviewCycle2DatetimeContracts(f *testing.F) {
	for _, seed := range []struct {
		raw, fraction string
		selector      uint16
	}{
		{"2026-08-01T1:30:00Z", "1234567", 0},
		{"2010-03-28T02:30:00", "1234569", 31},
		{"2010-10-31T02:30:00", "0000009", 531},
		{"0001-01-01T00:00:00Z", "9999999", 125},
		{"9999-12-31T23:59:59Z", "123456789123", 255},
	} {
		f.Add(seed.raw, seed.fraction, seed.selector)
	}
	f.Fuzz(func(t *testing.T, raw, fraction string, selector uint16) {
		moment, err := domainISOMoment(raw)
		again, againErr := domainISOMoment(raw)
		if (err == nil) != (againErr == nil) || !moment.Equal(again) {
			t.Fatal("datetime parsing is not deterministic")
		}
		if err != nil {
			if !OperationSortKey(raw).Equal(time.Time{}) || (TimeFilter{}).Contains(raw) {
				t.Fatal("invalid raw datetime gained a key/history match")
			}
		} else if moment.Nanosecond()%1000 != 0 || !(TimeFilter{}).Contains(raw) {
			t.Fatal("accepted source instant retained sub-microseconds")
		}
		// An independent generated negative assertion, not a parse/format oracle.
		bad := "2026-08-01T" + strconv.Itoa(int(selector%10)) + ":30:00Z"
		if _, err := domainISOMoment(bad); err == nil || (TimeFilter{}).Contains(bad) {
			t.Fatal("non-ISO one-digit hour accepted")
		}
		tc := reviewCycle2MoscowSourceCases[int(selector)%len(reviewCycle2MoscowSourceCases)]
		key, err := domainISOMoment(tc.text)
		_, offset := key.Zone()
		if err != nil || key.Unix() != tc.unixSecond || offset != tc.offset || key.Format("2006-01-02T15:04:05") != tc.text {
			t.Fatal("retained source fold/gap control changed")
		}
		if len(fraction) < 1 || len(fraction) > 64 {
			return
		}
		for _, r := range fraction {
			if r < '0' || r > '9' {
				return
			}
		}
		digits := fraction
		if len(digits) > 6 {
			digits = digits[:6]
		}
		digits += strings.Repeat("0", 6-len(digits))
		micro, err := strconv.Atoi(digits)
		if err != nil {
			t.Fatal(err)
		}
		text := "2026-08-01T12:30:00." + fraction + "+02:30:17"
		want := time.Date(2026, 8, 1, 12, 30, 0, micro*1000, time.FixedZone("source", 9017))
		f, err := NewTimeFilter(text, text)
		if err != nil || !OperationSortKey(text).Equal(want) || !f.Contains(text) {
			t.Fatal("generated precision control lost source truncation")
		}
	})
}

